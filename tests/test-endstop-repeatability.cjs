const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync('src/cnc-endstop-test.js','utf8');
assert(source.includes("for(let d=.5;d<=3.0001;d+=.5)"));
assert(source.includes("scan(available,releaseStart,releaseEnd,.1"));
assert(source.includes("Positioning move crossed or missed"));
assert(source.includes("No '+wantEnd+' transition occurred during the 0.1 mm measurement steps"));
assert(!/G28/.test(source));
assert(source.includes("['all','All — X, Y / Y1, Z / Z1']"));
assert(source.includes("targets=selected==='all'?['x','y','z']:[selected]"));
assert(!source.includes("s.idle_timeout?.state==='Printing'"));
assert(source.includes("||target===0)break"));
assert(source.includes("must be triggered at the home position before this group can be tested"));
const ctx={window:{PendantUI:{}},console};vm.createContext(ctx);vm.runInContext(source,ctx);
const api=ctx.window.CncEndstopTest,names=[['Y','stepper_y'],['Y1','y1']];
const cycles=Array.from({length:6},(_,i)=>({valid:true,stepper_y:{trip:i%2?.1:0,release:i%2?1.0:.9},y1:{trip:.1,release:1.1}}));
const summary=api.resultSummary(cycles,names);
assert.equal(summary.stepper_y.trip.average,.05);assert.equal(summary.stepper_y.trip.variation,.1);assert.equal(summary.stepper_y.release.average,.95);assert.equal(summary.stepper_y.release.variation,.1);
assert.equal(api.settled(cycles,names,.1),true);assert.equal(api.settled(cycles.slice(0,4),names,.1),false);
const missed=cycles.concat([{valid:false,stepper_y:{error:'missed'},y1:{trip:.1,release:1.1}}]);
assert.equal(api.resultSummary(missed,names).stepper_y.successful,6);assert.equal(api.resultSummary(missed,names).y1.successful,7);assert.equal(api.settled(missed,names,.1),true);
const drifting=Array.from({length:8},(_,i)=>({valid:true,stepper_y:{trip:i*.1,release:1+i*.1},y1:{trip:i*.1,release:1+i*.1}}));
assert.equal(api.settled(drifting,names,.1),false);
console.log('PASS: coarse discovery, fine-step acceptance, endstop summaries, per-switch misses and settling rules.');
